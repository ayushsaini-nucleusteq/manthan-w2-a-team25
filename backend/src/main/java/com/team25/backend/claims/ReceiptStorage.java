package com.team25.backend.claims;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.util.List;
import java.util.UUID;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Component;
import org.springframework.transaction.support.TransactionSynchronization;
import org.springframework.transaction.support.TransactionSynchronizationManager;

/**
 * Receipt files under RECEIPT_DIR (docker volume "receipts" at /data/receipts). Keys are generated by the
 * server ({@code claims/<claimId>/<receiptId>}), never taken from the client. Seeded demo receipts use keys
 * starting with {@code seed:} and are rendered on the fly as a one-page PDF (no files on disk).
 */
@Component
public class ReceiptStorage {

    public static final String SEED_PREFIX = "seed:";
    private static final Logger log = LoggerFactory.getLogger(ReceiptStorage.class);

    private final Path root;

    public ReceiptStorage(@Value("${app.receipts.dir}") String dir) throws IOException {
        this.root = Path.of(dir).toAbsolutePath().normalize();
        Files.createDirectories(root);
    }

    public String write(UUID claimId, UUID receiptId, byte[] bytes) {
        String key = "claims/" + claimId + "/" + receiptId;
        Path target = resolve(key);
        try {
            Files.createDirectories(target.getParent());
            Path tmp = Files.createTempFile(target.getParent(), "upload-", ".tmp");
            Files.write(tmp, bytes);
            Files.move(tmp, target, StandardCopyOption.REPLACE_EXISTING, StandardCopyOption.ATOMIC_MOVE);
        } catch (IOException e) {
            throw new UncheckedIOException("Could not store receipt", e);
        }
        return key;
    }

    public byte[] read(String key) {
        if (key.startsWith(SEED_PREFIX)) {
            // "seed:<label>#<receiptId>": the PDF depends only on the label, so planted duplicates share a hash.
            return SeedReceipts.pdf(key.substring(SEED_PREFIX.length()).split("#", 2)[0]);
        }
        try {
            return Files.readAllBytes(resolve(key));
        } catch (IOException e) {
            throw new UncheckedIOException("Receipt file is missing", e);
        }
    }

    public void delete(String key) {
        if (key == null || key.startsWith(SEED_PREFIX)) {
            return;
        }
        try {
            Files.deleteIfExists(resolve(key));
        } catch (IOException e) {
            log.warn("Could not delete receipt file {}", key, e);
        }
    }

    /** Deletes {@code keys} once the surrounding transaction commits (files of removed receipts). */
    public void deleteAfterCommit(List<String> keys) {
        if (keys.isEmpty()) {
            return;
        }
        TransactionSynchronizationManager.registerSynchronization(new TransactionSynchronization() {
            @Override
            public void afterCommit() {
                keys.forEach(ReceiptStorage.this::delete);
            }
        });
    }

    /** Deletes {@code key} if the surrounding transaction rolls back (a file written for a failed change). */
    public void deleteOnRollback(String key) {
        TransactionSynchronizationManager.registerSynchronization(new TransactionSynchronization() {
            @Override
            public void afterCompletion(int status) {
                if (status == STATUS_ROLLED_BACK) {
                    delete(key);
                }
            }
        });
    }

    private Path resolve(String key) {
        Path p = root.resolve(key).normalize();
        if (!p.startsWith(root)) {
            throw new IllegalArgumentException("Invalid receipt key");
        }
        return p;
    }

    /** Minimal one-page PDF for seeded receipts; deterministic so the stored SHA-256 matches. */
    public static final class SeedReceipts {

        private SeedReceipts() {
        }

        public static byte[] pdf(String text) {
            String safe = text.replaceAll("[^A-Za-z0-9 .,:/#-]", " ");
            String stream = "BT /F1 14 Tf 50 750 Td (ExpenseFlow demo receipt) Tj 0 -24 Td /F1 11 Tf (" + safe + ") Tj ET";
            String[] objects = {
                    "<< /Type /Catalog /Pages 2 0 R >>",
                    "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
                    "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>",
                    "<< /Length " + stream.length() + " >>\nstream\n" + stream + "\nendstream",
                    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>" };
            StringBuilder pdf = new StringBuilder("%PDF-1.4\n");
            int[] offsets = new int[objects.length];
            for (int i = 0; i < objects.length; i++) {
                offsets[i] = pdf.length();
                pdf.append(i + 1).append(" 0 obj\n").append(objects[i]).append("\nendobj\n");
            }
            int xref = pdf.length();
            pdf.append("xref\n0 ").append(objects.length + 1).append("\n0000000000 65535 f \n");
            for (int off : offsets) {
                pdf.append(String.format("%010d 00000 n \n", off));
            }
            pdf.append("trailer\n<< /Size ").append(objects.length + 1).append(" /Root 1 0 R >>\nstartxref\n")
                    .append(xref).append("\n%%EOF\n");
            return pdf.toString().getBytes(StandardCharsets.US_ASCII);
        }
    }
}
